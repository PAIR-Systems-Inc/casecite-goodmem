  const workflowPicker = page.getByRole('dialog', { name: 'Choose documents' });
  await workflowPicker.getByRole('checkbox', { name: /browser-agreement.txt/ }).check();
  await workflowPicker.getByRole('button', { name: 'Use 1 document', exact: true }).click();
  const approval = main.getByRole('region', { name: 'Approval', exact: true });
