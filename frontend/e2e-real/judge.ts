import { expect, type Page, type TestInfo } from '@playwright/test';

export async function exerciseJudgeIntelligence(page: Page, testInfo: TestInfo) {
  const main = page.locator('main[data-layout="main-content"]');
  await page.locator('[data-layout="left-sidebar"]').getByRole('button', { name: /^Judge Intel/ }).click();
  await main.getByLabel('Judge name', { exact: true }).fill('Jane Example');
  await main.getByRole('button', { name: 'Search judges', exact: true }).click();
  await expect(main.getByText('Showing 1 judges', { exact: true })).toBeVisible();
  await main.getByRole('button', { name: /Jane Example/ }).click();
  await expect(main.getByRole('heading', { name: /Jane Example/ })).toBeVisible({ timeout: 30_000 });
  await expect(main.getByText('Example University', { exact: true }).first()).toBeVisible();
  await expect(main.getByRole('heading', { name: 'Statistics', exact: true })).toBeVisible();
  await expect(main.getByText(/Separate-writing and writing metrics use explicitly identified authors only/)).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('judge-desktop.png'), fullPage: true, animations: 'disabled' });
  await main.getByRole('button', { name: 'Most Cited', exact: true }).click();
  await main.getByRole('button', { name: /Notice v. Example/ }).click();
  await expect(main.getByText(/The notice provision applies/).last()).toBeVisible();
  await expect(main.getByText(/I respectfully dissent/).last()).toBeVisible();

  const briefResponse = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/v1/chat' && r.request().method() === 'POST');
  await main.getByRole('button', { name: 'Generate Brief', exact: true }).click();
  const brief = await briefResponse;
  expect(brief.status()).toBe(200);
  const generated = await brief.json();
  expect(generated.judge_context).toMatchObject({ id: '42', task: 'brief' });
  expect(generated.content).toContain('Notice v. Example');
  expect(generated.content).not.toContain('unverified case-law reference removed');
  for (const section of ['QUICK FACTS', 'BACKGROUND', 'EDUCATION', 'CAREER & APPOINTMENTS', 'JUDICIAL RECORD ANALYSIS', 'NOTABLE CASES', 'COURTROOM STRATEGY']) {
    await expect(main.getByRole('heading', { name: section, exact: true })).toBeVisible();
  }

  await main.getByRole('button', { name: 'Select Files...', exact: true }).click();
  const picker = page.getByRole('dialog', { name: 'Select Documents', exact: true });
  await picker.getByRole('checkbox', { name: 'Select browser-agreement.txt', exact: true }).check();
  await picker.getByRole('button', { name: 'Apply Filter', exact: true }).click();
  await expect(main.getByRole('button', { name: '1 Selected', exact: true })).toBeVisible();
  const save = page.waitForResponse((r) => r.url().includes('/api/v1/workspace-sessions') && ['POST', 'PUT'].includes(r.request().method()) && r.request().postDataJSON()?.payload?.judgeMessages?.length === 2);
  const answerResponse = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/v1/chat' && r.request().method() === 'POST');
  await main.getByLabel('Ask about this judge', { exact: true }).fill('What do the profile and selected agreement say?');
  await main.getByRole('button', { name: 'Ask judge question', exact: true }).click();
  const answer = await answerResponse;
  expect(answer.status()).toBe(200);
  const result = await answer.json();
  expect(result.judge_context).toMatchObject({ id: '42', task: 'question' });
  expect(result.citations.some((c: { type: string; verified: boolean }) => c.type === 'judge_profile' && c.verified)).toBe(true);
  expect(result.citations.some((c: { type: string; verified: boolean; document_id: string }) => c.type === 'document' && c.verified && c.document_id)).toBe(true);
  await expect(main.getByText(/The agreement requires 30 days of notice/).last()).toBeVisible();
  const saved = await save;
  expect(saved.status()).toBeGreaterThanOrEqual(200);
  expect(saved.status()).toBeLessThan(300);
  const session = await saved.json();
  await main.getByRole('button', { name: 'Back to Search', exact: true }).click();
  const history = page.locator('[data-layout="right-panel"]');
  await history.getByRole('button', { name: 'History', exact: true }).click();
  await history.getByRole('button', { name: /Judge Intel.*Judge: Jane Example/ }).click();
  await expect(main.getByRole('heading', { name: 'QUICK FACTS', exact: true })).toBeVisible();
  await expect(main.getByText(/The agreement requires 30 days of notice/).last()).toBeVisible();
  await expect(main.getByRole('button', { name: '1 Selected', exact: true })).toBeVisible();
  const continuedSave = page.waitForResponse((r) => new URL(r.url()).pathname === `/api/v1/workspace-sessions/${session.id}` && r.request().method() === 'PUT');
  await main.getByRole('button', { name: 'Regenerate', exact: true }).click();
  expect((await continuedSave).status()).toBe(200);
  await expect(history.getByRole('button', { name: /Judge Intel.*Judge: Jane Example/ })).toHaveCount(1);
  await main.getByRole('heading', { name: 'Judicial Profile Brief', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('judge-brief-desktop.png'), animations: 'disabled' });
  await main.getByRole('heading', { name: 'Ask About This Judge', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('judge-question-desktop.png'), animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('[data-layout="left-sidebar"]')).not.toBeInViewport();
  await expect(page.locator('[data-layout="right-panel"]')).not.toBeInViewport();
  await page.screenshot({ path: testInfo.outputPath('judge-mobile.png'), fullPage: true, animations: 'disabled' });
  await main.getByRole('heading', { name: 'Judicial Profile Brief', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('judge-brief-mobile.png'), animations: 'disabled' });
  await main.getByRole('heading', { name: 'Ask About This Judge', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('judge-question-mobile.png'), animations: 'disabled' });
  await page.setViewportSize({ width: 1280, height: 720 });

  await main.getByRole('button', { name: 'Judge Data Only', exact: true }).click();
  await main.getByLabel('Ask about this judge', { exact: true }).fill('Pause this answer for the cancellation test');
  const pending = page.waitForRequest((r) => new URL(r.url()).pathname === '/api/v1/chat' && r.method() === 'POST');
  await main.getByRole('button', { name: 'Ask judge question', exact: true }).click();
  await pending;
  const aborted = page.waitForEvent('requestfailed', (r) => new URL(r.url()).pathname === '/api/v1/chat');
  await main.getByRole('button', { name: 'Clear', exact: true }).click();
  await aborted;
  await expect(main.getByText('Try asking:', { exact: true })).toBeVisible();
  await expect(main.getByLabel('Ask about this judge', { exact: true })).toBeEnabled();
  await main.getByRole('button', { name: 'Back to Search', exact: true }).click();
  const cached = page.waitForResponse((r) => r.url().includes('/judge-intel/build/42') && r.request().method() === 'POST');
  await main.getByRole('button', { name: /Jane Example/ }).click();
  expect((await (await cached).json()).status).toBe('cached');
  await expect(main.getByRole('heading', { name: /Jane Example/ })).toBeVisible();
}
