import { readFile } from 'node:fs/promises';
import { expect, type APIRequestContext, type Page, type TestInfo } from '@playwright/test';

export async function exerciseGoodMemOCR(page: Page, request: APIRequestContext, headers: Record<string, string>, testInfo: TestInfo) {
  const main = page.locator('main[data-layout="main-content"]');
  await page.goto('/documents');
  const pdf = await readFile('../server/internal/app/testdata/scanned_notice.pdf');
  const upload = page.waitForResponse((r) => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/documents');
  await page.getByLabel('Upload documents').setInputFiles({ name: 'scanned-notice.pdf', mimeType: 'application/pdf', buffer: pdf });
  const response = await upload;
  expect(response.status(), await response.text()).toBe(200);
  const document = await response.json() as { id: string };
  await expect.poll(async () => {
    const state = await request.get(`/api/v1/documents/${document.id}`, { headers });
    expect(state.status()).toBe(200);
    return (await state.json()).status;
  }, { timeout: 90_000, intervals: [1000] }).toBe('indexed');
  const original = await request.get(`/api/v1/documents/${document.id}/file`, { headers });
  expect(original.status()).toBe(200);
  expect(await original.body()).toEqual(pdf);
  const content = await request.get(`/api/v1/documents/${document.id}/content`, { headers });
  expect(content.status(), await content.text()).toBe(200);
  const text = await content.json();
  expect(text).toMatchObject({ text: 'SCANNED AGREEMENT\nNotice is 30 days.\nPayment is due monthly.', extraction: { method: 'goodmem_ocr', complete: true, page_count: 1, failed_pages: [] } });
  const cached = await request.get(`/api/v1/documents/${document.id}/content`, { headers });
  expect(cached.status()).toBe(200);
  expect(await cached.json()).toEqual(text);
  const pages = await request.get(`/api/v1/documents/${document.id}/pages`, { headers });
  expect(pages.status()).toBe(200);
  expect((await pages.json()).pages).toHaveLength(1);
  const pageImage = await request.get(`/api/v1/documents/${document.id}/pages/0/image`, { headers });
  expect(pageImage.status()).toBe(200);
  expect(pageImage.headers()['content-type']).toMatch(/^image\//);
  expect((await pageImage.body()).length).toBeGreaterThan(100);
  const research = await request.post('/api/v1/jobs', { headers, data: { kind: 'research', prompt: 'What notice does the scanned agreement require?', document_ids: [document.id] } });
  expect(research.status(), await research.text()).toBe(202);
  const jobId = (await research.json()).job_id as string;
  await expect.poll(async () => (await (await request.get(`/api/v1/jobs/${jobId}`, { headers })).json()).status, { timeout: 30_000 }).toBe('completed');
  const result = await (await request.get(`/api/v1/jobs/${jobId}`, { headers })).json();
  expect(result.result.citations).toHaveLength(1);
  expect(result.result.citations[0]).toMatchObject({ document_id: document.id, source: 'scanned-notice.pdf' });
  expect(result.result.citations[0].passage).toContain('Notice is 30 days.');

  await page.goto('/review-tables');
  await main.getByRole('button', { name: /Blank.*define your own fields/ }).click();
  await main.getByLabel('Review name', { exact: true }).fill('Scanned agreement review');
  await main.getByRole('button', { name: 'Add field', exact: true }).click();
  await main.getByLabel('Field 1 name', { exact: true }).fill('Notice');
  await main.getByLabel('Field 1 type', { exact: true }).selectOption('duration');
  await main.getByRole('button', { name: 'Create review', exact: true }).click();
  await expect(main.getByRole('heading', { name: 'Scanned agreement review', exact: true })).toBeVisible();
  await main.getByRole('button', { name: 'Documents', exact: true }).click();
  const picker = page.getByRole('dialog', { name: 'Choose documents' });
  await picker.getByRole('checkbox', { name: /scanned-notice.pdf/ }).check();
  await picker.getByRole('button', { name: 'Use 1 document', exact: true }).click();
  await main.getByRole('button', { name: 'Run review', exact: true }).click();
  const cell = main.getByRole('grid', { name: 'Review results' }).getByRole('gridcell').filter({ hasText: '30 days' });
  await expect(cell).toBeVisible({ timeout: 30_000 });
  await cell.click();
  const source = main.getByRole('complementary', { name: 'Cell source and review' });
  await expect(source.getByText('Verified against the document', { exact: true })).toBeVisible();
  await expect(source.getByText('Text extracted using OCR · page 1', { exact: true })).toBeVisible();
  await expect(source.locator('mark')).toHaveText('Notice is 30 days.');
  await expect(page.getByText('Review finished: 1 cell, 1 verified.', { exact: true })).toBeHidden({ timeout: 10_000 });
  await source.locator('mark').scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath('ocr-desktop.png'), fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await source.scrollIntoViewIfNeeded();
  await expect(source.locator('mark')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('ocr-mobile.png'), fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 1280, height: 720 });
}
