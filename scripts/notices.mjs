// Regenerate notices for the libraries distributed in the binary and web bundle.
import {readFileSync, writeFileSync, existsSync, readdirSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..');
const read=p=>readFileSync(p,'utf8').replace(/\r\n/g,'\n');
const license=dir=>existsSync(dir)?readdirSync(dir,{withFileTypes:true}).filter(e=>e.isFile()&&/^(licen[cs]e(?:[.-].*)?|ofl\.txt|mit-license)$/i.test(e.name)).map(e=>read(resolve(dir,e.name))).join('\n'):'';
let text=`# Third-party notices — CaseCite GoodMem\n\nCaseCite Copyright 2026 Thomas Unise.\nGoodMem edition modifications: 2026 CaseCite GoodMem contributors.\n\nDerived from https://github.com/thomasunise/casecite at 6605cb3474cf0c2894080af216d5fed2a81fc997, under Apache-2.0. See LICENSE.\n\nGenerated by node scripts/notices.mjs. The following notices accompany libraries in the Go executable and frontend bundle. Node build tools and the separately deployed GoodMem/PostgreSQL services have their own licenses.\n`;
const packages=execFileSync('go',['list','-deps','-json','./cmd/casecite'],{cwd:resolve(root,'server'),encoding:'utf8',maxBuffer:16*1024*1024}).trim().split(/\n(?=\{)/).map(s=>JSON.parse(s));
const modules=[...new Map(packages.filter(p=>p.Module).map(p=>[p.Module.Path,p.Module])).values()];
const goroot=execFileSync('go',['env','GOROOT'],{encoding:'utf8'}).trim();
text+='\n## Go standard library\n\n'+license(goroot)+'\n';
for(const m of modules){if(m.Main)continue;const contents=m.Dir?license(m.Dir):'';if(!contents)throw new Error(`License missing for ${m.Path}; run go mod download all`);text+=`\n## ${m.Path} ${m.Version}\n\n${contents}\n`;}
const seen=new Set();
for(const workspace of ['frontend','word-addin']) {
 const lock=JSON.parse(read(resolve(root,workspace,'package-lock.json')));
 for(const [path,pkg] of Object.entries(lock.packages)){
  if(!path||pkg.dev||pkg.optional)continue;
  const name=path.replace('node_modules/','');
  const key=`${name}@${pkg.version}`;if(seen.has(key))continue;seen.add(key);
  const contents=license(resolve(root,workspace,path));
  if(!contents)throw new Error(`License missing for ${workspace}/${path}; run npm ci`);
  text+=`\n## ${name} ${pkg.version} (${pkg.license || 'see below'})\n\n${contents}\n`;
 }
}
writeFileSync(resolve(root,'NOTICE.md'),text.trimEnd()+'\n');
console.log('Updated NOTICE.md');
